export function computeReturnRow(item: ReturnLineItem): ComputedReturnRow {
  const c = item.causes;
  const totalClassifiedUnits =
    c.aCobrar + c.xFecha + c.vacio + c.proxVencer + c.vencido + c.abomba + c.lechozo;

  const copByCause: Record<ReturnCauseKey, number> = {
    aCobrar: c.aCobrar * item.unitCost,
    xFecha: c.xFecha * item.unitCost,
    vacio: c.vacio * item.unitCost,
    proxVencer: c.proxVencer * item.unitCost,
    vencido: c.vencido * item.unitCost,
    abomba: c.abomba * item.unitCost,
    lechozo: c.lechozo * item.unitCost,
  };

  const commercialValueCOP =
    copByCause.aCobrar + copByCause.proxVencer + copByCause.vencido;
  const qualityValueCOP =
    copByCause.vacio + copByCause.xFecha + copByCause.abomba + copByCause.lechozo;
  const totalValueCOP = commercialValueCOP + qualityValueCOP;

  let reconciliationStatus: ComputedReturnRow['reconciliationStatus'] = 'CUADRADO';
  if (item.qtyToReceive !== totalClassifiedUnits) {
    if (
      totalClassifiedUnits === 0 &&
      (item.movementType === 'DEGUSTACION' || item.movementType === 'REINGRESO_BUENO')
    ) {
      reconciliationStatus = 'JUSTIFICADO_NO_AVERIA';
    } else {
      reconciliationStatus = 'REVISAR';
    }
  }

  let primaryCauseKey: ReturnCauseKey | null = null;
  let maxUnits = 0;
  (Object.keys(c) as ReturnCauseKey[]).forEach((k) => {
    if (c[k] > maxUnits) {
      maxUnits = c[k];
      primaryCauseKey = k;
    }
  });

  return {
    ...item,
    totalClassifiedUnits,
    reconciliationStatus,
    discrepancyUnits: item.qtyToReceive - totalClassifiedUnits,
    copByCause,
    totalValueCOP,
    commercialValueCOP,
    qualityValueCOP,
    primaryCauseKey,
  };
}

export function computeZoneMetrics(zone: ZoneSummary) {
  const u = zone.unitsByCause;
  const m = zone.copByCause;

  const totalUnits =
    u.aCobrar + u.xFecha + u.vacio + u.proxVencer + u.vencido + u.abomba + u.lechozo;

  const commercialCOP = m.aCobrar + m.proxVencer + m.vencido;
  const commercialUnits = u.aCobrar + u.proxVencer + u.vencido;

  const qualityCOP = m.vacio + m.xFecha + m.abomba + m.lechozo;
  const qualityUnits = u.vacio + u.xFecha + u.abomba + m.lechozo > 0 ? u.vacio + u.xFecha + u.abomba + u.lechozo : 0;

  const totalCOP = commercialCOP + qualityCOP;

  const pctTotalOverSales =
    zone.monthlySalesCOP > 0 ? (totalCOP / zone.monthlySalesCOP) * 100 : 0;
  const pctCommercialOverSales =
    zone.monthlySalesCOP > 0 ? (commercialCOP / zone.monthlySalesCOP) * 100 : 0;
  const pctQualityOverSales =
    zone.monthlySalesCOP > 0 ? (qualityCOP / zone.monthlySalesCOP) * 100 : 0;

  return {
    ...zone,
    totalUnits,
    totalCOP,
    commercialCOP,
    commercialUnits,
    qualityCOP,
    qualityUnits,
    pctTotalOverSales,
    pctCommercialOverSales,
    pctQualityOverSales,
  };
}
